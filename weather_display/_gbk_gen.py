# -*- coding: utf-8 -*-
# 生成 GBK 字节表，供 Arduino 草图使用
import sys

texts = [
  "气象监测系统","太阳能相变","粮食干燥","联网获取中","连接失败","获取失败","请检查WiFi","稍后重试","设置","默认",
  "城市","天气","气温","湿度","风速","风向","日期","时间","星期","更新","今天","明天","后天","预报","实时","实测","对比","差值","数据","信号","强度","弱","良","优","在线","离线","气象","材料","系统",
  "晴","多云","阴","小雨","中雨","大雨","暴雨","雷阵雨","阵雨","小雪","中雪","雪","雾","霾","扬沙","沙尘暴","晴间多云","晴转多云","多云转晴","多云转阴","阴转多云","小雨转阴",
  "东","南","西","北","东北","东南","西北","西南","风","微风","级","最高","最低","日出","日落","紫外线","适宜","不适宜","注意","建议","高温","高湿","干燥",
  "适宜太阳能干燥","可进行晾晒","建议提前收粮","不宜露天干燥","注意防雨","太阳能不足","辅助加热","注意扬尘","霉变风险",
  "一","二","四","五","六","日","三","周","月","零","周","零"
]

seen = set()
out_lines = []
for t in texts:
    key = t
    if key in seen:
        continue
    seen.add(key)
    try:
        b = t.encode("gbk")
        pairs = ", ".join("0x" + b[i:i+1].hex().upper() for i in range(len(b)))
        out_lines.append(f"// {t}\n{{{pairs}, 0x00}},")
    except Exception as e:
        out_lines.append(f"// ERR {t}: {e}")

print("\n".join(out_lines))
print(f"\n[total {len(seen)} unique strings]", file=sys.stderr)